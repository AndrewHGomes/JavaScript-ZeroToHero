// AULA - Loop While
let w = 0;

while (w <= 3) {
  console.log("w agora é " + w);
  w++;
}

// EXERCÍCIO - Loop While
let numero = 1;

while (numero <= 5) {
  console.log("Número " + numero);
  numero++;
}

// AULA - Loop Do While
let dw = 3;

do {
  console.log("dw agora é " + dw);
  dw--;
} while (dw >= 0);

// EXERCÍCIO - Loop Do While
let contador = 1;

do {
  console.log("Contador é " + contador);
  contador++;
} while (contador <= 5);
